def body_for(sections):
    return ''.join(
        '<section><h2>' + escape(heading) + '</h2>'
        + ''.join('<p>' + escape(paragraph) + '</p>' for paragraph in paragraphs)
        + '</section>'
        for heading, paragraphs in sections
    )


def enhance():
    sitemap = ROOT / 'sitemap.xml'
    xml = sitemap.read_text(encoding='utf-8')
    updates = {}
    for slug, sections in ARTICLES.items():
        url = BASE + '/ar/ibiza-intelligence/' + slug + '/'
        path = ROOT / 'ar' / 'ibiza-intelligence' / slug / 'index.html'
        html = path.read_text(encoding='utf-8')
        matches = list(BODY_RE.finditer(html))
        if len(matches) != 1:
            raise SystemExit(f'Phase 129 expected one article body: {url}')
        match = matches[0]
        old_body = match.group(2)
        new_body = body_for(sections)
        old_headings = tuple(re.findall(r'<h2>(.*?)</h2>', old_body, re.S))
        if old_body != new_body and old_headings != OLD_HEADINGS:
            raise SystemExit(f'Phase 129 refusing to overwrite an unexpected article body: {url}')
        html = html[:match.start(2)] + new_body + html[match.end(2):]
        html = rewrite_article_schema(html, url, LASTMOD)
        html = MOD_META_RE.sub('', html)
        html = html.replace('</head>', f'<meta property="article:modified_time" content="{LASTMOD}"></head>', 1)
        updates[path] = html

        pattern = re.compile(rf'(<url><loc>{re.escape(url)}</loc>)(?:<lastmod>[^<]+</lastmod>)?')
        xml, count = pattern.subn(lambda m: m.group(1) + f'<lastmod>{LASTMOD}</lastmod>', xml)
        if count != 1:
            raise SystemExit(f'Phase 129 expected one sitemap entry: {url}')

    # Validate every input before writing any generated page.
    for path, html in updates.items():
        path.write_text(html, encoding='utf-8')
    sitemap.write_text(xml, encoding='utf-8')
    print('PASS: Phase 129 — four Arabic Black Book articles now contain topic-specific guidance from their English editions; only their verified modification dates were updated')


if __name__ == '__main__':
    enhance()
